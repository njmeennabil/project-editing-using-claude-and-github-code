/* BUMI360 — field check, crop guide, comparison and rotation.
   Data comes from data/crops.js (window.BUMI_DATA), generated by database/export_json.py. */
(function () {
  "use strict";

  var DATA = window.BUMI_DATA;
  var CROPS = DATA.crops;
  var $ = function (id) { return document.getElementById(id); };

  /* ---------- Helpers ---------- */
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function num(n) { return n == null ? "–" : String(Math.round(n * 100) / 100); }
  function range(a, b) {
    if (a == null && b == null) return "–";
    if (a == null) return "≤ " + num(b);
    if (b == null) return "≥ " + num(a);
    return a === b ? num(a) : num(a) + "–" + num(b);
  }
  function phRange(c) { return c.soil.ph_min.toFixed(1) + "–" + c.soil.ph_max.toFixed(1); }
  function maturity(c) {
    if (c.maturity_min_days == null) return "No data";
    return (c.maturity_min_days === c.maturity_max_days ? "~" + c.maturity_min_days : range(c.maturity_min_days, c.maturity_max_days)) + " days";
  }
  function water(c) { return c.water_min_mm == null ? "Keep moist" : range(c.water_min_mm, c.water_max_mm) + " mm"; }
  function byCode(code) { return CROPS.filter(function (c) { return c.code === code; })[0]; }

  var LABEL = { ok: "Suitable", warn: "Suitable with management", bad: "Less suitable", none: "Incomplete" };
  var RANK = { ok: 0, warn: 1, bad: 2, none: 3 };

  /* ---------- Suitability rules ---------- */
  function checkPh(c, ph) {
    var s = c.soil;
    var r = { name: "Soil pH", range: "Range " + phRange(c), meter: { d: [3.5, 8.5], lo: s.ph_min, hi: s.ph_max, v: ph },
              you: isNaN(ph) ? null : "Yours: " + ph.toFixed(1) };
    if (isNaN(ph)) { r.status = "none"; r.msg = "Enter your soil pH."; return r; }
    if (s.ph_danger_below != null && ph < s.ph_danger_below) {
      r.status = "bad"; r.title = "Danger";
      r.msg = "Below pH " + num(s.ph_danger_below) + " there is a risk of aluminium toxicity. Raise the pH before planting.";
    } else if (ph < s.ph_min) {
      r.status = "bad"; r.title = "Too acidic";
      r.msg = (s.ph_min - ph).toFixed(1) + " below the minimum. Raise soil pH, for example with agricultural lime or dolomite.";
    } else if (ph > s.ph_max) {
      r.status = "bad"; r.title = "Too alkaline";
      r.msg = (ph - s.ph_max).toFixed(1) + " above the maximum.";
    } else {
      r.status = "ok"; r.title = "Suitable"; r.msg = "Within the recommended range.";
    }
    return r;
  }

  function checkTemp(c, t) {
    var r = { name: "Temperature", range: "Optimum " + range(c.temp_min_c, c.temp_max_c) + "°C",
              meter: { d: [10, 40], lo: c.temp_min_c, hi: c.temp_max_c, v: t }, you: isNaN(t) ? null : "Yours: " + num(t) + "°C" };
    if (isNaN(t)) { r.status = "none"; r.msg = "Enter your average temperature."; return r; }
    var diff = t < c.temp_min_c ? c.temp_min_c - t : t > c.temp_max_c ? t - c.temp_max_c : 0;
    if (diff === 0) { r.status = "ok"; r.title = "Optimal"; r.msg = "Within the optimum temperature range."; return r; }
    r.status = diff <= 2 ? "warn" : "bad";
    r.title = t < c.temp_min_c ? "Too cool" : "Too hot";
    r.msg = num(diff) + "°C " + (t < c.temp_min_c ? "below" : "above") + " the optimum range. Growth and yield may be affected.";
    return r;
  }

  function checkWater(c, w) {
    if (c.water_min_mm == null) {
      return { name: "Water per season", range: "No mm figure", meter: null, you: null, status: "info",
               title: "Keep the soil moist", msg: c.water_note || "" };
    }
    var r = { name: "Water per season", range: "Needs " + range(c.water_min_mm, c.water_max_mm) + " mm",
              meter: { d: [0, 1200], lo: c.water_min_mm, hi: c.water_max_mm, v: w }, you: isNaN(w) ? null : "Yours: " + num(w) + " mm" };
    if (isNaN(w)) { r.status = "none"; r.msg = "Enter the water available per season."; return r; }
    if (w < c.water_min_mm) {
      var short = c.water_min_mm - w;
      r.status = short > c.water_min_mm * 0.5 ? "bad" : "warn"; r.title = "Not enough";
      r.msg = num(short) + " mm short of the minimum. Plan extra irrigation.";
    } else if (w > c.water_max_mm) {
      r.status = "warn"; r.title = "Excess water";
      r.msg = num(w - c.water_max_mm) + " mm above the requirement. Make sure drainage is good." + (c.water_note ? " " + c.water_note : "");
    } else {
      r.status = "ok"; r.title = "Sufficient";
      r.msg = "Enough water for the season." + (c.water_target_mm ? " Aim for about " + num(c.water_target_mm) + " mm for high yield." : "");
    }
    return r;
  }

  function assess(c, input) {
    var checks = [checkPh(c, input.ph), checkTemp(c, input.temp), checkWater(c, input.water)];
    var st = checks.map(function (x) { return x.status; });
    var overall = st.indexOf("none") >= 0 ? "none" : st.indexOf("bad") >= 0 ? "bad" : st.indexOf("warn") >= 0 ? "warn" : "ok";
    return { crop: c, checks: checks, status: overall };
  }

  /* ---------- Field check UI ---------- */
  function meterHtml(m) {
    if (!m) return "";
    var pct = function (x) { return Math.max(0, Math.min(100, (x - m.d[0]) / (m.d[1] - m.d[0]) * 100)); };
    var lo = pct(m.lo), hi = pct(m.hi);
    return '<div class="meter" aria-hidden="true"><span class="band" style="left:' + lo.toFixed(1) + "%;width:" + Math.max(hi - lo, 1).toFixed(1) + '%"></span>' +
      (isNaN(m.v) ? "" : '<span class="mark" style="left:' + pct(m.v).toFixed(1) + '%"></span>') + "</div>";
  }

  function checkHtml(x) {
    return '<li class="check s-' + x.status + '">' +
      '<div class="check-top"><span class="check-name">' + esc(x.name) + '</span><span class="check-range">' + esc(x.range) +
      (x.you ? " · " + esc(x.you) : "") + "</span></div>" +
      meterHtml(x.meter) +
      '<p class="check-msg">' + (x.title ? "<strong>" + esc(x.title) + ".</strong> " : "") + esc(x.msg) + "</p></li>";
  }

  function resultHtml(r) {
    var c = r.crop;
    return '<article class="panel result">' +
      '<div class="result-head"><div><h4>' + esc(c.name) + '</h4><p class="sub">' + esc(c.local_name) + " · <i>" + esc(c.scientific_name) + "</i></p></div>" +
      '<span class="pill s-' + r.status + '">' + LABEL[r.status] + "</span></div>" +
      '<ul class="checks">' + r.checks.map(checkHtml).join("") + "</ul>" +
      '<div class="result-foot"><button class="link-btn" type="button" data-guide="' + esc(c.code) + '">View the ' + esc(c.name.toLowerCase()) + " growing guide →</button></div>" +
      "</article>";
  }

  function readForm() {
    var f = function (id) { var v = $(id).value.trim(); return v === "" ? NaN : parseFloat(v.replace(",", ".")); };
    return { ph: f("ph"), temp: f("temp"), water: f("water"), choice: $("crop-choice").value };
  }

  function renderCheck() {
    var input = readForm();
    var list = input.choice === "all" ? CROPS : CROPS.filter(function (c) { return c.code === input.choice; });
    var results = list.map(function (c) { return assess(c, input); });
    if (input.choice === "all") results.sort(function (a, b) { return RANK[a.status] - RANK[b.status] || a.crop.id - b.crop.id; });

    var conds = [
      isNaN(input.ph) ? "pH not entered" : "pH " + input.ph.toFixed(1),
      isNaN(input.temp) ? "temperature not entered" : num(input.temp) + "°C",
      isNaN(input.water) ? "water not entered" : num(input.water) + " mm per season"
    ].join(" · ");

    var html;
    if (input.choice === "all") {
      var count = { ok: 0, warn: 0, bad: 0, none: 0 };
      results.forEach(function (r) { count[r.status]++; });
      html = "<h3>" + (count.none ? "Complete the form for a full result"
        : count.ok + " of " + results.length + " crops suit your field as it is") + "</h3>" +
        '<p class="conds">' + esc(conds) + '</p><div class="chips">' +
        ["ok", "warn", "bad"].filter(function (s) { return count[s]; }).map(function (s) {
          return '<span class="pill s-' + s + '">' + count[s] + " " + LABEL[s].toLowerCase() + "</span>";
        }).join("") + "</div>";
    } else {
      html = "<h3>" + esc(results[0].crop.name) + ": " + LABEL[results[0].status].toLowerCase() + "</h3>" + '<p class="conds">' + esc(conds) + "</p>";
    }
    $("summary").innerHTML = html;
    $("results").className = "result-list" + (results.length > 1 ? " many" : "");
    $("results").innerHTML = results.map(resultHtml).join("");
    save();
  }

  /* Remember the last readings in this browser only */
  var KEY = "bumi360-field-v1";
  var DEFAULTS = { ph: "5.8", temp: "28", water: "600", choice: "all" };
  function save() {
    try { localStorage.setItem(KEY, JSON.stringify({ ph: $("ph").value, temp: $("temp").value, water: $("water").value, choice: $("crop-choice").value })); } catch (e) {}
  }
  function restore() {
    try {
      var s = JSON.parse(localStorage.getItem(KEY) || "null");
      if (!s) return;
      setForm(s);
      $("sample-note").textContent = "Your last readings have been restored.";
    } catch (e) {}
  }
  function setForm(s) {
    ["ph", "temp", "water"].forEach(function (id) { if (s[id] != null) $(id).value = s[id]; });
    if (s.choice && $("crop-choice").querySelector('option[value="' + s.choice + '"]')) $("crop-choice").value = s.choice;
  }

  /* ---------- Crop guide ---------- */
  var current = CROPS[0].code;

  function renderTabs() {
    $("crop-tabs").innerHTML = CROPS.map(function (c) {
      var sel = c.code === current;
      return '<button class="crop-tab" type="button" role="tab" id="tab-' + esc(c.code) + '" aria-controls="guide-panel" aria-selected="' + sel + '" tabindex="' + (sel ? 0 : -1) + '" data-code="' + esc(c.code) + '">' +
        "<span>" + esc(c.name) + "</span><small>" + esc(c.local_name) + "</small></button>";
    }).join("");
    $("guide-panel").setAttribute("aria-labelledby", "tab-" + current);
  }

  function block(title, body, wide) {
    return '<section class="guide-block' + (wide ? " wide" : "") + '"><h4>' + esc(title) + "</h4>" + body + "</section>";
  }

  function renderGuide() {
    var c = byCode(current), s = c.soil, out = [];
    out.push('<div class="guide-top"><div><p class="sub"><i>' + esc(c.scientific_name) + "</i> · " + esc(c.local_name) + "</p><h3>" + esc(c.name) + "</h3></div>" +
      '<div class="badges"><span class="badge">' + esc(c.type) + "</span>" + (c.fixes_nitrogen ? '<span class="badge">Fixes nitrogen</span>' : "") +
      (c.source ? '<span class="badge">Source: ' + esc(c.source) + "</span>" : "") + "</div></div>");

    out.push('<dl class="stat-row">' +
      '<div class="stat"><dt>Soil pH</dt><dd>' + phRange(c) + "</dd></div>" +
      '<div class="stat"><dt>Temperature</dt><dd>' + range(c.temp_min_c, c.temp_max_c) + "°C</dd></div>" +
      '<div class="stat"><dt>Water / season</dt><dd>' + esc(water(c)) + (c.water_target_mm ? "<small>~" + num(c.water_target_mm) + " mm for high yield</small>" : "") + "</dd></div>" +
      '<div class="stat"><dt>Maturity</dt><dd>' + esc(maturity(c)) + (c.maturity_note ? "<small>" + esc(c.maturity_note) + "</small>" : "") + "</dd></div></dl>");

    var g = [];
    var soil = [["Texture", s.texture], ["Drainage", s.drainage]];
    if (s.ph_danger_below != null) soil.push(["Avoid", "pH below " + num(s.ph_danger_below)]);
    if (s.note) soil.push(["Note", s.note]);
    g.push(block("Soil", '<dl class="kv">' + soil.map(function (p) { return "<div><dt>" + esc(p[0]) + "</dt><dd>" + esc(p[1]) + "</dd></div>"; }).join("") + "</dl>"));

    var wat = [["Critical stages", c.critical_water_stages.length ? c.critical_water_stages.join(", ") : "No data"]];
    if (c.water_note) wat.push(["Note", c.water_note]);
    wat.push(["Key nutrient", c.key_nutrient], ["Nitrogen need", c.nitrogen_need]);
    g.push(block("Water and nutrients", '<dl class="kv">' + wat.map(function (p) { return "<div><dt>" + esc(p[0]) + "</dt><dd>" + esc(p[1]) + "</dd></div>"; }).join("") + "</dl>"));

    if (c.npk.length) {
      g.push(block("NPK dose (kg/ha)", '<div class="table-scroll"><table><thead><tr><th>Source</th><th>When</th><th>N</th><th>P₂O₅</th><th>K₂O</th></tr></thead><tbody>' +
        c.npk.map(function (b) {
          return "<tr><td>" + esc(b.source) + "</td><td>" + esc(b.condition) + (b.note ? '<br><span class="muted">' + esc(b.note) + "</span>" : "") + "</td>" +
            '<td class="num">' + range(b.n_min, b.n_max) + '</td><td class="num">' + range(b.p2o5_min, b.p2o5_max) + '</td><td class="num">' + range(b.k2o_min, b.k2o_max) + "</td></tr>";
        }).join("") + "</tbody></table></div>"));
    }
    if (c.fertiliser_programme.length) {
      g.push(block("Fertiliser programme", '<div class="table-scroll"><table><thead><tr><th>Product</th><th>Rate</th><th>When</th></tr></thead><tbody>' +
        c.fertiliser_programme.map(function (p) {
          return "<tr><td>" + esc(p.product) + (p.note ? '<br><span class="muted">' + esc(p.note) + "</span>" : "") + "</td>" +
            '<td class="num">' + range(p.rate_min, p.rate_max) + " " + esc(p.unit) + "</td><td>" + esc(p.timing) + "</td></tr>";
        }).join("") + "</tbody></table></div>"));
    }
    if (c.special_nutrients.length) {
      g.push(block("Special nutrients", '<ul class="plain-list">' + c.special_nutrients.map(function (n) {
        var rate = n.rate_min_kg_ha != null ? " " + range(n.rate_min_kg_ha, n.rate_max_kg_ha) + " kg/ha" : "";
        return "<li><strong>" + esc(n.nutrient) + "</strong>: " + esc(n.role) +
          (n.product ? ". " + esc(n.product) + rate : "") + (n.timing ? ", " + esc(n.timing).toLowerCase() : "") + ".</li>";
      }).join("") + "</ul>"));
    }
    if (c.spacing.length) {
      g.push(block("Plant spacing", '<ul class="plain-list">' + c.spacing.map(function (j) {
        var row = range(j.row_min_cm, j.row_max_cm), plant = range(j.plant_min_cm, j.plant_max_cm);
        var txt = row !== "–" && plant !== "–" ? row + " × " + plant + " cm (between rows × within row)"
          : row !== "–" ? row + " cm between rows" : plant + " cm between plants";
        return "<li>" + (j.variety ? "<strong>" + esc(j.variety) + "</strong>: " : "") + esc(txt) + "</li>";
      }).join("") + "</ul>"));
    }
    if (c.practices.length) {
      g.push(block("Good practice", '<ul class="practice-list">' + c.practices.map(function (p) {
        return '<li><span class="tag">' + esc(p.category) + "</span><span>" + esc(p.text) + "</span></li>";
      }).join("") + "</ul>", true));
    }
    var rot = DATA.rotation.filter(function (r) { return r.before === c.name || r.after === c.name; });
    if (rot.length) {
      g.push(block("Rotation", '<ul class="plain-list">' + rot.map(function (r) {
        return "<li><strong>" + esc(r.before) + " → " + esc(r.after) + "</strong>" + (r.yield_gain_pct ? " (+" + num(r.yield_gain_pct) + "% yield)" : "") + ". " + esc(r.note) + "</li>";
      }).join("") + "</ul>", true));
    }
    out.push('<div class="guide-grid">' + g.join("") + "</div>");
    $("guide-panel").innerHTML = out.join("");
  }

  function selectCrop(code, focusTab) {
    current = code;
    renderTabs();
    renderGuide();
    var tab = $("tab-" + code);
    if (tab) {
      // Scroll only the tab strip sideways, never the page.
      var strip = $("crop-tabs");
      var left = tab.offsetLeft - strip.offsetLeft, right = left + tab.offsetWidth;
      if (left < strip.scrollLeft) strip.scrollLeft = left;
      else if (right > strip.scrollLeft + strip.clientWidth) strip.scrollLeft = right - strip.clientWidth;
      if (focusTab) tab.focus({ preventScroll: true });
    }
  }

  /* ---------- Compare & rotation ---------- */
  function renderCompare() {
    var head = "<thead><tr><th>Crop</th><th>Type</th><th>Soil pH</th><th>Temp (°C)</th><th>Water / season</th><th>Key nutrient</th><th>Nitrogen</th><th>Maturity</th></tr></thead>";
    var rows = CROPS.map(function (c) {
      return '<tr><th scope="row">' + esc(c.name) + "<small>" + esc(c.local_name) + "</small></th><td>" + esc(c.type) + '</td><td class="num">' + phRange(c) +
        '</td><td class="num">' + range(c.temp_min_c, c.temp_max_c) + '</td><td class="num">' + esc(water(c)) + "</td><td>" + esc(c.key_nutrient) +
        "</td><td>" + esc(c.nitrogen_need) + '</td><td class="num">' + esc(maturity(c)) + "</td></tr>";
    }).join("");
    $("compare-table").innerHTML = head + "<tbody>" + rows + "</tbody>";
  }

  function renderRotation() {
    $("rotation-list").innerHTML = DATA.rotation.map(function (r) {
      return '<article class="panel rot"><div class="rot-flow"><span>' + esc(r.before) + '</span><span class="rot-arrow" aria-label="then">→</span><span>' + esc(r.after) + "</span>" +
        (r.yield_gain_pct ? '<span class="rot-gain">+' + num(r.yield_gain_pct) + "% yield</span>" : "") + '</div><p class="muted">' + esc(r.note) + "</p></article>";
    }).join("");
    $("rotation-notes").innerHTML = DATA.rotation_notes.map(function (n) { return "<li>" + esc(n) + "</li>"; }).join("");
  }

  /* ---------- Wiring ---------- */
  CROPS.forEach(function (c) {
    var o = document.createElement("option");
    o.value = c.code; o.textContent = c.name + " (" + c.local_name + ")";
    $("crop-choice").appendChild(o);
  });
  $("fact-crops").textContent = CROPS.length;
  $("year").textContent = new Date().getFullYear();

  restore();
  var form = $("field-form");
  form.addEventListener("submit", function (e) { e.preventDefault(); renderCheck(); $("summary").scrollIntoView({ block: "nearest" }); });
  form.addEventListener("input", renderCheck);
  form.addEventListener("change", renderCheck);
  $("reset-btn").addEventListener("click", function () {
    setForm(DEFAULTS); renderCheck();
    $("sample-note").textContent = "These are example values. Replace them with your own field readings.";
  });

  $("results").addEventListener("click", function (e) {
    var b = e.target.closest("[data-guide]");
    if (!b) return;
    selectCrop(b.getAttribute("data-guide"));
    $("crops").scrollIntoView();
    $("guide-panel").focus({ preventScroll: true });
  });

  $("crop-tabs").addEventListener("click", function (e) {
    var b = e.target.closest("[data-code]");
    if (b) selectCrop(b.getAttribute("data-code"));
  });
  $("crop-tabs").addEventListener("keydown", function (e) {
    if (e.key !== "ArrowRight" && e.key !== "ArrowLeft") return;
    var i = CROPS.findIndex(function (c) { return c.code === current; });
    i = (i + (e.key === "ArrowRight" ? 1 : -1) + CROPS.length) % CROPS.length;
    selectCrop(CROPS[i].code, true);
    e.preventDefault();
  });

  var menuBtn = $("menu-btn"), nav = $("site-nav");
  menuBtn.addEventListener("click", function () {
    var open = nav.classList.toggle("open");
    menuBtn.setAttribute("aria-expanded", String(open));
  });
  nav.addEventListener("click", function (e) {
    if (e.target.closest("a")) { nav.classList.remove("open"); menuBtn.setAttribute("aria-expanded", "false"); }
  });

  renderCheck();
  selectCrop(current);
  renderCompare();
  renderRotation();
})();
