#!/usr/bin/env python3
"""Export tanaman.db to docs/data/ as English data for the static BUMI360 website.

Writes crops.json (for other apps/APIs) and crops.js (loaded by docs/index.html).
"""
import json
import sys
from pathlib import Path

from crop_data import MissingTranslation, load_data

OUT = Path(__file__).resolve().parent.parent / "docs" / "data"
OUT.mkdir(parents=True, exist_ok=True)

try:
    data = load_data()
except MissingTranslation as e:
    print("Missing English translation for these texts. Add them to translations_en.py:", file=sys.stderr)
    for s in e.texts:
        print(f"  {s!r}", file=sys.stderr)
    sys.exit(1)

text = json.dumps(data, ensure_ascii=False, indent=1)
(OUT / "crops.json").write_text(text + "\n", encoding="utf-8")
(OUT / "crops.js").write_text(
    "// Generated by database/export_json.py. Do not edit by hand.\n"
    f"window.BUMI_DATA = {text};\n", encoding="utf-8")
print(f"Done: {OUT / 'crops.json'} and crops.js ({len(data['crops'])} crops)")
